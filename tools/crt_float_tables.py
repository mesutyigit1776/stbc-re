"""Write src/engine/CrtFloatTables.inc: the power of ten tables of the C run time of stbc.exe.

Run with: tools/.venv/bin/python -I tools/crt_float_tables.py [--check]
The tables hold 12-byte extended values (five mantissa words and one exponent word). The positive table
starts at 0x97d850 and the negative table at 0x97d9b0. Each has 29 entries: 10^1 to 10^7, 10^8 to 10^56
in steps of 8, then steps of 64, 512 and the entry 10^4096. --check compares the file with the exe.
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXE = os.path.join(ROOT, "game", "stbc.exe")
OUT = os.path.join(ROOT, "src", "engine", "CrtFloatTables.inc")
TABLES = (("kPow10Pos", 0x97D850), ("kPow10Neg", 0x97D9B0))
ENTRIES = 29
ENTRY_SIZE = 12


def section_bytes(data, address):
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    count = struct.unpack_from("<H", data, pe + 6)[0]
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    base = struct.unpack_from("<I", data, pe + 24 + 28)[0]
    for i in range(count):
        _, vsize, va, rsize, raw = struct.unpack_from("<8sIIII", data, pe + 24 + optional_size + 40 * i)
        if base + va <= address < base + va + min(vsize, rsize):
            return raw + address - base - va
    raise SystemExit("address 0x%x is not in a section" % address)


def render(data):
    lines = ["// Generated by tools/crt_float_tables.py from stbc.exe. Do not edit.", ""]
    for name, address in TABLES:
        offset = section_bytes(data, address)
        lines.append("// 0x%x" % address)
        lines.append("static const unsigned char %s[%d][%d] = {" % (name, ENTRIES, ENTRY_SIZE))
        for i in range(ENTRIES):
            entry = data[offset + i * ENTRY_SIZE: offset + (i + 1) * ENTRY_SIZE]
            lines.append("    {" + ", ".join("0x%02x" % b for b in entry) + "},")
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def main(argv):
    data = open(EXE, "rb").read()
    text = render(data)
    if "--check" in argv:
        if open(OUT).read() != text:
            print("CrtFloatTables.inc differs from the exe")
            return 1
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
